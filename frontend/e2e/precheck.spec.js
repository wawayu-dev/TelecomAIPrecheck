import { test, expect } from '@playwright/test'

async function login(page, actor) {
  await page.getByLabel('演示身份').selectOption(actor)
  const password = process.env[`DEMO_${actor.toUpperCase()}_PASSWORD`]
  if (!password) throw new Error(`Missing DEMO_${actor.toUpperCase()}_PASSWORD`)
  await page.getByLabel('账户密码').fill(password)
  await page.getByRole('button', { name: '登录并进入工单' }).click()
  await expect(page.locator('.host-identity strong')).toHaveText(actor)
}

test('桌面：宿主路由 → 预审失败转人工 → 修订确认 → 审计查询', async ({ page }, info) => {
  await page.setViewportSize({ width: 1440, height: 1050 })
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  await page.goto('/host/tickets/DEMO-003/precheck')
  await login(page, 'operator')
  await expect(page.getByRole('heading', { level: 1 })).toContainText('DEMO-003')
  await expect(page.locator('.evidence-panel')).toContainText('¥ 20.00')
  const created = page.waitForResponse(response => response.request().method() === 'POST' && response.url().includes('/api/ai-prechecks/tickets/'))
  await page.getByRole('button', { name: /开始 AI 预审|发起新一轮预审/ }).click()
  const payload = await (await created).json()
  expect(Math.abs(Date.now() - Date.parse(payload.run.createdAt))).toBeLessThan(30000)
  expect(Math.abs(Date.parse(payload.run.createdAt) - Date.parse(payload.evidenceSnapshot.capturedAt))).toBeLessThan(5000)
  await expect(page.locator('.result-panel')).toContainText('已转人工')
  await expect(page.locator('.result-panel')).toContainText('模型未配置')
  await expect(page.locator('.result-panel')).toContainText('账单与订购金额不一致')
  await expect(page.locator('#review-summary')).toHaveCount(0)
  await page.getByRole('button', { name: '切换身份' }).click()
  await login(page, 'reviewer')
  await expect(page).toHaveURL(/DEMO-003\/precheck$/)
  await page.getByLabel('人工摘要').fill('合成演示：账单金额30元，订购月费20元，需核实计费差异。')
  await page.getByLabel('处理建议', { exact: true }).selectOption('VERIFY_BILLING')
  await page.getByLabel('复核依据').fill('根据 BILL-003 与 ORDER-003 核对，转业务人员核实，不执行退费。')
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: info.outputPath('review-before-confirm.png'), fullPage: true })
  await page.getByRole('button', { name: '确认处理建议', exact: true }).click()
  await expect(page.locator('.human-panel')).toContainText('已确认')
  await expect(page.getByRole('button', { name: '确认处理建议', exact: true })).toHaveCount(0)
  await expect(page.locator('.timeline li')).toHaveCount(3)
  await page.getByRole('button', { name: '切换身份' }).click()
  await login(page, 'auditor')
  await expect(page.locator('.timeline')).toContainText('人工确认建议')
  await expect(page.locator('.human-panel')).toContainText('reviewer')
  await expect(page.getByRole('button', { name: /开始 AI 预审|发起新一轮预审/ })).toHaveCount(0)
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: info.outputPath('audit-complete.png'), fullPage: true })
  expect(errors).toEqual([])
})

test('窄屏：缺少授权场景 → 人工驳回，布局不横向溢出', async ({ page }, info) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/host/tickets/DEMO-002/precheck')
  await login(page, 'operator')
  await expect(page.locator('.evidence-panel')).toContainText('证据缺失不等于违规扣费')
  const created = page.waitForResponse(response => response.request().method() === 'POST' && response.url().includes('/api/ai-prechecks/tickets/'))
  await page.getByRole('button', { name: /开始 AI 预审|发起新一轮预审/ }).click()
  const payload = await (await created).json()
  expect(Math.abs(Date.now() - Date.parse(payload.run.createdAt))).toBeLessThan(30000)
  expect(Math.abs(Date.parse(payload.run.createdAt) - Date.parse(payload.evidenceSnapshot.capturedAt))).toBeLessThan(5000)
  await expect(page.locator('.result-panel')).toContainText('缺少授权凭据')
  await page.getByRole('button', { name: '切换身份' }).click()
  await login(page, 'reviewer')
  await page.getByLabel('人工摘要').fill('合成演示：授权凭据缺失，需要进一步补充材料。')
  await page.getByLabel('复核依据').fill('当前资料不足，不据此认定违规扣费。')
  await page.getByRole('button', { name: '驳回预审' }).click()
  await expect(page.locator('.human-panel')).toContainText('已驳回')
  await expect(page.locator('.timeline li')).toHaveCount(3)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: info.outputPath('mobile-rejected.png'), fullPage: true })
})
